# core/task_context.py
"""
Пропуск: сквозной номер, который носит с собой каждое дело (фаза 1, блок 3).

Зачем этот файл появился
------------------------
В журнале действий с версии схемы 2 лежит колонка `correlation_id`, и до
этого блока в неё НИКОГДА ничего не писали — всегда NULL (проверено грепом
18.08.2026: во всём проекте есть только запись, ни одного чтения). Следствие
было не «на будущее», а прямо сегодня: у журнала действий нет вообще никакой
пометки о запуске. Номер сессии живёт только в стопках отмены, а в журнале —
нет. Поэтому на вопрос «что ты делал» Джарвис отвечал вперемешку: сегодняшнее
и то, что было неделю назад, без возможности различить.

Три правила, которые важнее самого кода
---------------------------------------
1. ЯВНО ПЕРЕДАННЫЙ ПРОПУСК ВСЕГДА СИЛЬНЕЕ ТОГО, ЧТО В КОНТЕКСТЕ.
   Записано до того, как появился второй способ: в фазе 1б у gate.dispatch
   появится параметр ctx, и если половина кода будет брать пропуск из
   контекста, а половина из параметра, появятся два источника правды. Они
   разойдутся, и понять это будет негде. Порядок старшинства — один.

2. ПРОПУСК СТАВИТСЯ ТОЛЬКО ЧЕРЕЗ `with bind(...)`, никогда «поставить и
   забыть». Причина замерена, а не придумана: main.py вызывает инструменты
   двадцатью `run_in_executor`, а это ПУЛ потоков, и потоки в нём
   переиспользуются. Пропуск, оставленный в таком потоке, всплыл бы в
   следующем чужом деле. Возврат прежнего значения обязателен.

3. ДАТА В НОМЕРЕ ДЕЛА — ЯРЛЫК, А НЕ РАСЧЁТНАЯ ГРАНИЦА. Она местная, потому
   что владелец услышит её вслух («дело от 18 августа»). Квотные сутки —
   совсем другое понятие, они живут РОВНО В ОДНОМ месте (metering.quota_day)
   и считаются по Pacific. Три разных «дня» в одном проекте — готовая мина;
   единственная защита от неё — написать прямо, какой для чего.

Замер, на котором стоит устройство (18.08.2026, песочница)
----------------------------------------------------------
    внутри самого цикла   — контекст виден
    asyncio.to_thread     — контекст виден
    run_in_executor       — контекста НЕТ
    threading.Thread      — контекста НЕТ

`main.py` зовёт инструменты через `run_in_executor`, то есть ВНУТРИ
инструмента пропуска не будет. Спасает то, что запись в журнал идёт ПОСЛЕ
`await`, уже вернувшись в цикл, — там пропуск виден. Поэтому правок в
main.py этот блок не требует вовсе. Тест
`test_run_in_executor_does_not_carry_the_context` закрепляет замер: без него
через полгода кто-то напишет код внутри рабочего потока, будет ждать номер
и молча его не получит.
"""
from __future__ import annotations

import contextvars
import itertools
import secrets
import threading
from datetime import datetime, timezone

# Предел рекурсии: 0 — владелец, 1 — агент, 2 — подчинённый агента. Глубже
# не бывает. Число живёт здесь одно и проверяется в одном месте.
MAX_DEPTH = 2

# Корзины расхода (заготовка под О23, подбюджеты выключены до месяца
# эксплуатации). Заполнять поле надо с первого дня, иначе решать будет не на чем.
BUCKETS = ("dialog", "task", "background")

_ROOT_ROLE = "owner"
_MAIN_ROLE = "main"

_CURRENT: contextvars.ContextVar = contextvars.ContextVar("jarvis_task_ctx",
                                                          default=None)
_LOCK = threading.Lock()
_run_id = None
_dialog = None
_sessions = itertools.count(1)


# -- Номера ---------------------------------------------------------------

def new_run_id(*, now=None) -> str:
    """Номер запуска: '20260818T014530Z-a3f1'.

    Сортируется, читается глазами, не путается с номером дела. Случайный
    хвост нужен по двум причинам: два запуска в одну секунду (бывает при
    отладке) и прыжок часов назад — уникальность не должна зависеть от часов
    (эта грабля уже случалась на шаге 24).
    """
    stamp = (now or datetime.now(timezone.utc)).strftime("%Y%m%dT%H%M%SZ")
    return f"{stamp}-{secrets.token_hex(2)}"


def run_id() -> str:
    """Номер ЭТОГО запуска. Считается один раз и живёт с процессом."""
    global _run_id
    with _LOCK:
        if _run_id is None:
            _run_id = new_run_id()
        return _run_id


def new_session_id() -> str:
    """Номер сессии: '20260818T014530Z-a3f1#1'. Новый на КАЖДЫЙ вызов.

    Почему это не тот же номер, что у запуска, хотя очень похоже.
    -----------------------------------------------------------
    В блоке 3 я сначала сделал номер сессии равным номеру запуска — план Р2
    просит убрать лишние номерки, и в живой работе `new_session()` зовётся
    ровно один раз за процесс, так что числа совпадали. Существующий тест
    отмены (`test_unscoped_undo_is_limited_to_current_session`) покраснел и
    оказался прав: у этих двух номеров РАЗНЫЕ обязанности.

      номер запуска — один на процесс. Его дело: подписать строки журнала,
                      чтобы «что ты делал» отличало сегодняшнее от прошлого;
      номер сессии  — новый на каждое начало сессии. Его дело: держать
                      «отмени последнее» внутри текущей сессии, чтобы отмена
                      никогда не дотянулась до правок прошлой (тот самый
                      случай с report.txt).

    Слить их — значит получить ошибку, которой сегодня нет, а завтра есть:
    как только сессия начнётся дважды за процесс, отмена полезет в чужое.
    Поэтому номер сессии ПРОИЗВОДИТСЯ от номера запуска, но остаётся своим:
    в логах сразу видно, какому запуску он принадлежит, а обязанность не
    потеряна. Номерков по-прежнему меньше, чем было: случайных 32 знаков,
    которые ни о чём не говорили, больше нет.
    """
    with _LOCK:
        n = next(_sessions)
    return f"{run_id()}#{n}"


def format_task_id(day, seq: int) -> str:
    """Номер дела: 'T-20260818-001'.

    Дата МЕСТНАЯ — это человеческий ярлык (см. правило 3 в шапке).
    Ширина три знака ради читаемости; на 1000-м деле за сутки номер станет
    длиннее и перестанет сортироваться как строка. Не ограничиваем и не
    паникуем: у владельца потолок 2 задачи одновременно и 10 инициативных
    реплик в сутки, а по номеру дела ничего не упорядочивается — для порядка
    есть created_utc.
    """
    if isinstance(day, str):
        stamp = day
    else:
        stamp = day.strftime("%Y%m%d")
    return f"T-{stamp}-{int(seq):03d}"


def today_stamp(*, now=None) -> str:
    """Местная дата для номера дела. Отдельной функцией — это шов для теста."""
    return (now or datetime.now()).strftime("%Y%m%d")


# -- Пропуск --------------------------------------------------------------

class TaskCtx:
    """Кто просил, для какого дела и на какой глубине.

    Неизменяем нарочно: меняется только счётчик шагов. Пропуск гуляет между
    потоками, и всё, что можно испортить снаружи, однажды испортят.
    """

    __slots__ = ("run_id", "task_id", "parent_id", "depth", "agent_role",
                 "bucket", "origin_chain", "_steps")

    def __init__(self, *, run_id: str, task_id: str | None = None,
                 parent_id: str | None = None, depth: int = 0,
                 agent_role: str | None = None, bucket: str = "dialog",
                 origin_chain: tuple = (_ROOT_ROLE,)):
        if bucket not in BUCKETS:
            raise ValueError(
                f"корзина {bucket!r} не из списка {BUCKETS}: "
                "молча подставлять свою нельзя")
        if depth > MAX_DEPTH:
            raise ValueError(
                f"глубина {depth} больше предела {MAX_DEPTH}: "
                "рекурсия агентов кончается здесь")
        self.run_id = str(run_id)
        self.task_id = task_id
        self.parent_id = parent_id
        self.depth = int(depth)
        self.agent_role = agent_role
        self.bucket = bucket
        self.origin_chain = tuple(origin_chain)
        self._steps = itertools.count(1)

    # -- Строка для журнала -----------------------------------------------

    def correlation(self, step: int | None = None) -> str:
        """'run:<номер>/task:<номер>/step:<n>' — то, что ложится в колонку.

        Колонка `correlation_id` существует с версии схемы 2, поэтому блоку 3
        не нужна ни одна миграция. Дела ещё нет — на его месте прочерк, а не
        пустота: пустое место в строке невозможно отличить от обрезанной.
        """
        n = next(self._steps) if step is None else int(step)
        task = self.task_id or "-"
        return f"run:{self.run_id}/task:{task}/step:{n}"

    @staticmethod
    def parse(text: str) -> dict:
        """Разобрать строку обратно. Собрали — значит умеем и прочесть."""
        out = {"run": None, "task": None, "step": None}
        for part in str(text or "").split("/"):
            name, _, value = part.partition(":")
            if name == "run":
                out["run"] = value or None
            elif name == "task":
                out["task"] = None if value in ("", "-") else value
            elif name == "step":
                out["step"] = int(value) if value.isdigit() else None
        return out

    # -- Подчинённые ------------------------------------------------------

    def child(self, *, agent_role: str, task_id: str | None = None,
              bucket: str = "task") -> "TaskCtx":
        """Пропуск подчинённого: глубина +1, цепочка +роль.

        В цепочку идёт РОЛЬ, а не имя агента: ядро имён не знает (I21).
        Добавить третьего агента должно быть можно правкой одного yaml.
        """
        if self.depth >= MAX_DEPTH:
            raise ValueError(
                f"глубже {MAX_DEPTH} делегировать нельзя: "
                f"цепочка уже {' -> '.join(self.origin_chain)}")
        return TaskCtx(
            run_id=self.run_id,
            task_id=task_id,
            parent_id=self.task_id,
            depth=self.depth + 1,
            agent_role=agent_role,
            bucket=bucket,
            origin_chain=self.origin_chain + (str(agent_role),),
        )

    def __repr__(self) -> str:
        return (f"TaskCtx(run={self.run_id}, task={self.task_id}, "
                f"depth={self.depth}, chain={'->'.join(self.origin_chain)})")


# -- Кто сейчас говорит ---------------------------------------------------

def dialog_ctx() -> TaskCtx:
    """Пропуск разговора: тот, под которым идёт всё, о чём попросили голосом.

    Существует всегда. Дела у него нет — есть номер запуска, и этого уже
    достаточно, чтобы отличить сегодняшний разговор от прошлогоднего.

    Номер запуска берётся ДО замка нарочно. `run_id()` берёт тот же самый
    замок, а обычный замок не повторный: вызов под замком означал бы мёртвую
    хватку — процесс встаёт молча и навсегда. Поймано тестом при первом же
    прогоне 18.08.2026. Взять RLock было бы короче, но это лечение симптома:
    вложенных захватов в этом файле быть не должно вообще.
    """
    global _dialog
    rid = run_id()
    with _LOCK:
        if _dialog is None or _dialog.run_id != rid:
            _dialog = TaskCtx(run_id=rid, bucket="dialog",
                              origin_chain=(_ROOT_ROLE, _MAIN_ROLE))
        return _dialog


def current(explicit: TaskCtx | None = None) -> TaskCtx:
    """Пропуск, под которым сейчас надо записывать.

    Порядок старшинства (правило 1 в шапке): явный параметр -> контекст ->
    разговор. Никогда не падает и никогда не отдаёт пустоту: запись без
    номера — это ровно то, что мы здесь лечим.
    """
    if explicit is not None:
        return explicit
    got = _CURRENT.get()
    return got if got is not None else dialog_ctx()


class bind:
    """`with bind(ctx):` — поставить пропуск и ОБЯЗАТЕЛЬНО вернуть прежний.

    Именно менеджер контекста, а не функция-сеттер, и это не стиль: потоки в
    пуле `run_in_executor` переиспользуются, и забытый пропуск всплыл бы в
    следующем чужом деле. Токен возврата даёт contextvars — на нём и стоим.
    """

    __slots__ = ("_ctx", "_token")

    def __init__(self, ctx: TaskCtx | None):
        self._ctx = ctx
        self._token = None

    def __enter__(self) -> TaskCtx | None:
        self._token = _CURRENT.set(self._ctx)
        return self._ctx

    def __exit__(self, *exc) -> bool:
        if self._token is not None:
            _CURRENT.reset(self._token)
            self._token = None
        return False


def reset_for_tests() -> None:
    """Забыть номер запуска и пропуск разговора. Зовёт tests/conftest.py.

    Весь прогон — один процесс, то есть один «запуск». Без сброса номер
    первого теста достался бы всем остальным, и сторожа были бы зелёными по
    неверной причине — та же грабля, что с защёлкой схемы в блоке 1.
    """
    global _run_id, _dialog, _sessions
    with _LOCK:
        _run_id = None
        _dialog = None
        _sessions = itertools.count(1)
    _CURRENT.set(None)
