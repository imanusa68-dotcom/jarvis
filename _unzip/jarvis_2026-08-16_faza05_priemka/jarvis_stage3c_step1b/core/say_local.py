# -*- coding: utf-8 -*-
"""
Собственный рот Джарвиса — системный голос Windows (SAPI5).

Зачем он вообще нужен. Тот голос, который владелец слышит при живой
связи, синтезируется на стороне поставщика и приходит готовым звуком.
Нет провода — нет и звука, поэтому без сети ядро только печатало в окно.
Здесь голос берётся из самой Windows: бесплатно, без установок, без прав
администратора и без единого байта наружу.

Границы, которые здесь держатся жёстко:

1. Ленивые импорты. pywin32 есть только на Windows; верхний импорт убил бы
   весь проект на любой другой машине и в половине тестов.
2. Русский голос ищется по коду языка (419), а НЕ по имени «Irina». Имя — это
   случайность конкретной сборки Windows; код языка — правило.
3. Речь асинхронная (флаг 1), НО функция дожидается конца речи.
   Это не придирка, а цена одного вечера. В первой редакции шага 29
   функция отдавала фразу синтезатору и тут же возвращала True.
   Объект SpVoice погибал вместе с коротким потоком раньше, чем
   успевал зазвучать звук: ошибки нет, возврат True, тишина в комнате.
   Замирания окна бояться не нужно: main.py зовёт рот в своём потоке.
4. Один рот за раз. Ответ и напоминание могут совпасть по времени;
   без замка владелец услышит два голоса поверх друг друга.
4. Любая беда — молчание и строка в консоль, никогда не падение. Нет голоса —
   остаётся текст в окне, это хуже, но не смертельно.
5. Кто решает, можно ли говорить — НЕ этот файл. Замок «только когда сети
   нет» живёт в main.py, где известно состояние сессии.
"""
from __future__ import annotations

import os
import sys
import threading

# Код языка русского в Windows (0x419). SAPI отдаёт его шестнадцатеричной
# строкой, иногда списком через точку с запятой.
_RUSSIAN = "419"

# SVSFlagsAsync: синтезатор начинает говорить и сразу возвращает управление.
_ASYNC = 1

# Сколько миллисекунд ждём конца фразы. Полминуты — с запасом на самый
# длинный ответ ядра (меню из семи умений читается около десяти секунд).
# Без потолка зависший синтезатор держал бы поток речи вечно.
_WAIT_MS = 30000

# Сколько секунд вторая фраза ждёт своей очереди у замка.
_LOCK_WAIT_S = 60.0

# Замок на один рот: ответ и напоминание не говорят хором.
_MOUTH = threading.Lock()

# Служебные приставки окна. Глазам они нужны, ушам — нет.
_PREFIXES = ("jarvis:", "sys:", "ai:", "you:")

# То, что в окне выглядит разделителем, вслух превращается в кашу.
_TO_PAUSE = ("\u00b7", "\u2022", "\u2014", "\u2013", "|")

# Приказ модели из actions/reminder.py. Модели он адресован, владельцу — нет.
_ORDER_MARK = "[\u041d\u0410\u041f\u041e\u041c\u0418\u041d\u0410\u041d\u0418\u0415]"


def clean_for_ears(text: str) -> str:
    """
    Текст для ушей: без приставки «Jarvis:» и без типографской мебели.

    В окне строка выглядит как «Jarvis: время и дата · напоминания · заметка».
    Зачитанная дословно, она звучит как бред с перечислением знаков.
    """
    s = (text or "").strip()
    low = s.lower()
    for p in _PREFIXES:
        if low.startswith(p):
            s = s[len(p):].strip()
            break
    for mark in _TO_PAUSE:
        s = s.replace(mark, ",")
    while ",," in s:
        s = s.replace(",,", ",")
    s = " ".join(s.split())
    s = s.replace(" ,", ",")
    return s.strip(" ,")


def human_reminder(text: str) -> str:
    """
    Д-5. В окне владельца оказывалась служебная команда для модели:
    «[НАПОМИНАНИЕ] Немедленно скажи мне вслух следующее напоминание: ...».
    С появлением голоса это перестало быть косметикой: Джарвис зачитал бы
    приказ самому себе вслух. Модели команда по-прежнему уходит слово в слово.
    """
    s = (text or "").strip()
    if not s.startswith(_ORDER_MARK):
        return s
    body = s.split(":", 1)[1].strip() if ":" in s else ""
    if not body:
        return s
    return "\u041d\u0430\u043f\u043e\u043c\u0438\u043d\u0430\u043d\u0438\u0435: " + body


def _muted_for_tests() -> bool:
    """
    Прогон тестов не имеет права говорить вслух.

    Стенды шагов 26–28 гоняют настоящий ответ ядра десятки раз подряд. Без
    этого предохранителя команда `python -m pytest -q` на машине владельца
    превратилась бы в беспрерывное бормотание на полминуты.

    Предохранитель срабатывает только для ЖИВОГО COM. Тесты с двойником
    проверяют логику полностью и ничего не теряют.
    """
    if os.environ.get("JARVIS_VOICE_IN_TESTS"):
        return False
    return "pytest" in sys.modules


def _default_dispatch(name: str):
    """Живой COM. Шов для тестов: в них сюда никто не заходит."""
    import pythoncom
    import win32com.client
    try:
        # Речь идёт из чужого потока (ответ ядра, напоминание) — без этой
        # строки COM молча откажет. Тот же приём уже используется в слое
        # осознания (core/awareness/_explorer.py).
        pythoncom.CoInitialize()
    except Exception:
        pass
    return win32com.client.Dispatch(name)


def _prefer_russian(voice) -> bool:
    """Выбрать русский голос, если он есть. Нет — говорим тем, что есть."""
    try:
        for token in voice.GetVoices():
            try:
                lang = str(token.GetAttribute("Language") or "")
            except Exception:
                continue
            if _RUSSIAN in lang:
                voice.Voice = token
                return True
    except Exception:
        pass
    return False


def _wait_until_done(voice) -> bool:
    """
    Дождаться конца фразы. Без этого шага голоса не будет вовсе.

    Асинхронный Speak только ставит фразу в очередь. Если сразу после
    этого отпустить объект синтезатора и закончить поток, очередь умирает
    вместе с ним — ровно это и произошло у владельца вечером 13.08.2026.

    Старые двойники без этого метода не должны ломать рот, поэтому
    метод спрашивается мягко.
    """
    waiter = getattr(voice, "WaitUntilDone", None)
    if waiter is None:
        return False
    try:
        waiter(_WAIT_MS)
        return True
    except Exception:  # noqa: BLE001
        return False


def say(text: str, dispatch=None) -> bool:
    """
    Сказать вслух и дождаться конца фразы. True — фраза произнесена.

    Зовите только из фонового потока: функция держит вызывающего до конца
    речи. main.py так и делает, окно не замирает.

    Функция никогда не бросает исключений: её зовут из фоновых потоков, где
    некому ловить ошибку, а молчаливо умерший поток — это пропавшие
    напоминания через час.
    """
    speech = clean_for_ears(text)
    if not speech:
        return False
    if dispatch is None and _muted_for_tests():
        return False
    make = dispatch or _default_dispatch
    if not _MOUTH.acquire(timeout=_LOCK_WAIT_S):
        print("[Voice] \u0440\u043e\u0442 \u0437\u0430\u043d\u044f\u0442 \u0441\u043b\u0438\u0448\u043a\u043e\u043c \u0434\u043e\u043b\u0433\u043e")
        return False
    try:
        voice = make("SAPI.SpVoice")
        _prefer_russian(voice)
        voice.Speak(speech, _ASYNC)
        _wait_until_done(voice)
        return True
    except Exception as e:  # noqa: BLE001
        print("[Voice] \u043c\u0435\u0441\u0442\u043d\u044b\u0439 \u0433\u043e\u043b\u043e\u0441 \u043d\u0435 \u0432\u044b\u0448\u0435\u043b: %s" % type(e).__name__)
        return False
    finally:
        _MOUTH.release()
