# core/blackbox.py
"""
Чёрный ящик: запись ответов модели, чтобы сбой можно было прокрутить заново
(фаза 1, блок 6). Ни одной новой миграции: таблицы `mx_bb_body` и `mx_bb_head`
стоят с блока 2, индекс уборки — тоже.

ЗАЧЕМ ЭТОТ ФАЙЛ
---------------
Главная беда таких систем — сбой, случившийся один раз. Владелец говорит «ты
вчера сделал ерунду», а воспроизвести это нечем: ответ модели каждый раз
новый. Записанный ответ превращает неповторимый сбой в обычный тест, и
разбор перестаёт стоить квоту: при потолке 120 вызовов в сутки это
единственный способ отлаживаться вообще (I40).

ПИШЕМ ТОЛЬКО ТО, ЧТО НЕЛЬЗЯ ПЕРЕСЧИТАТЬ
---------------------------------------
В теле живут два вида строк: промпт и ответ модели. Всё остальное — какой
инструмент позвали, что решил гейт, чем кончилось — код посчитает сам заново,
если подставить те же ответы. Ответ модели угадать нельзя, поэтому его надо
хранить; остальное при тех же ответах повторяется.

Вердикты гейта здесь НЕ дублируются нарочно. В шапке `core/audit_log.py`
написано прямо, что читатели фазы 1 (то есть этот файл) обязаны читать его
журнал. Он уже есть и уже версионирован. Две тетради об одном рано или поздно
начинают спорить, и тогда встаёт вопрос «какая из них сегодня правда».

ПИШЕМ АРГУМЕНТ `prompt`, А НЕ ТО, ЧТО УШЛО В МОДЕЛЬ
---------------------------------------------------
Разница не косметическая. Разбор экрана посылает снимок в родном разрешении
(замерено: около полумегабайта на кадр). Байты картинки живут в отдельном
аргументе и склеиваются с текстом только в слое поставщика. Пишем текст —
в базе не будет ни одного байта картинки; писали бы тело запроса — каждый
вопрос про экран весил бы сотни килобайт.

ОТПЕЧАТОК ПОЛНОГО ПРОМПТА — САМАЯ ВАЖНАЯ ДЕТАЛЬ ФОРМЫ
-----------------------------------------------------
Потолок на строку обязателен: замер по коду показал четыре места, где обрезки
нет вовсе (параметры упавшего шага, текст ошибки при перепланировании,
сниппет поисковика, число сравниваемых предметов), и ни одного ограничения на
размер ответа модели во всём проекте. Но обрезанный промпт никогда бы не
совпал при воспроизведении. Поэтому рядом с текстом лежит отпечаток ПОЛНОГО
промпта, посчитанный ДО обрезки и ДО заглушения: искать можно по отпечатку, а
текст остаётся для чтения глазами. Обрезка перестаёт ломать воспроизведение.

Отпечаток считается от сырого промпта нарочно: при воспроизведении код
соберёт ровно сырой промпт, и отпечаток от заглушённого текста с ним не
совпал бы. Секрета отпечаток не выдаёт — по нему нельзя восстановить текст.

СУТКИ ПОСТАВЩИКА ЭТОТ ФАЙЛ НЕ СЧИТАЕТ
-------------------------------------
Дата приходит параметром `day` от того, кто уже взял талон у учёта расхода.
Так решено по двум причинам, и вторая важнее первой. Первая: знание о том,
как считаются сутки поставщика, живёт ровно в одном месте проекта, и второе
вычисление было бы багом, который всплывает раз в полгода. Вторая: раз дата у
записи и у строки расхода приходит из одного талона, они физически НЕ МОГУТ
разойтись — а разошлись бы обязательно, считай их каждый сам.

ПОЧЕМУ ЗАПИСЬ РОЖДАЕТСЯ «ПРОВАЛЕННОЙ»
-------------------------------------
Это не выбор, а форма таблицы. Колонка исхода объявлена обязательной и без
значения по умолчанию, а значения «ещё открыта» в списке исходов нет. Снять
обязательность нельзя без пересборки таблицы, которую запрещает правило
«только добавлять». Значит запись обязана родиться с каким-то исходом — и
единственный безопасный выбор «провалено»: пока мы не дошли до конца, худшее
предположение честнее оптимистичного. Открытость видна по пустому `closed_utc`.

БРОШЕННЫЕ ЗАПИСИ ЗАКРЫВАЮТСЯ ПРИ СТАРТЕ, И ЭТО НЕ МЕЛОЧЬ
--------------------------------------------------------
Уборка обязана пропускать открытые записи, иначе однажды удалит середину
живой задачи. Но запись, брошенную падением, не закроет никто — и её тело с
дословной речью владельца лежало бы ВЕЧНО, мимо всех сроков хранения. Лечение
взято у учёта расхода: в момент, когда этот процесс ещё не открыл ни одной
своей записи, всё открытое заведомо из прошлой жизни. Закрываем это как
«прервано».

Сметание зовётся РОВНО ОДИН РАЗ и именно ДО первой своей записи. В блоке 5
первая версия такой уборки звалась на каждом вызове и убивала живой резерв
соседнего потока — счётчик врал вдвое. Здесь та же ловушка: позови сметание
позже, и оно закроет нашу же живую запись.

ЭТОТ ФАЙЛ НИЧЕГО НЕ ПЕЧАТАЕТ
----------------------------
Запись зовут из общей двери к модели, а у неё есть сторож, который требует,
чтобы удачный вызов не печатал НИ ОДНОЙ строки. Поэтому здесь тот же порядок,
что у журнала двери: молча, а потери видны числом через `lost_count()`.
Печать внутри `except` уже роняла вызов на консоли cp1251 (блок 5).

ЗАПИСЬ НИКОГДА НЕ ЛОМАЕТ ДЕЛО
-----------------------------
База может быть занята соседним потоком, диск полон, схема стара. Любая
неудача здесь — это `False` и плюс один к счётчику потерь, но никогда не
исключение наверх и никогда не отказ от вызова модели. Потерянная строка
записи стоит несравнимо меньше, чем несделанное дело.

СВОЕГО ЗАМКА У ЭТОГО ФАЙЛА БОЛЬШЕ НЕТ (блок 7)
----------------------------------------------
До блока 7 здесь стоял свой замок. Он СНЯТ, а не оставлен рядом, и это не
уборка ради красоты. Два замка вокруг одной базы дают РАЗНЫЙ ПОРЯДОК захвата:
поток А держит кассу и ждёт замок ящика, поток Б наоборот — и оба стоят
навсегда. Живьём это «Джарвис завис при запуске», и искать будут в микрофоне.

Заодно исчезла тонкость, которую я сам же описал в блоке 6: `purge` и функции
чтения нарочно не брали замок, когда соединение передавали снаружи. Это
работало, но было ровно тем местом, где обратный порядок и завёлся бы.

Память этого файла (`_seq`, `_mine`, `_swept`, `_purged_day`) теперь стережёт
замок кассы: весь код, который её трогает, выполняется ВНУТРИ записи, то есть
по очереди. Свой замок был бы вторым замком об одном и том же.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
from datetime import datetime, timedelta, timezone

# Словарь видов строк тела. Список ЗАКРЫТ: смысл каждого вида знает ядро, а
# незнакомый вид молча испортил бы воспроизведение (оно ищет пары
# «промпт → ответ»). Значения взяты из формы таблицы, заведённой в блоке 2.
KINDS = ("speech_in", "prompt", "model_out", "tool_call", "gate_verdict",
         "report", "spoken")

# Из семи видов в фазе 1 пишутся ДВА. Остальные недостижимы, и это названо
# вслух, а не умолчано: речь владельца и произнесённое живут в голосовом
# файле, который заморожен, а отчёты появятся вместе с агентами.
WRITTEN_NOW = ("prompt", "model_out")

# Исходы записи. ВНИМАНИЕ: это НЕ список статусов отчёта из agent/contracts.py.
# Там вместо «прервано» стоит «отказано»: агент может ОТКАЗАТЬСЯ (гейт не
# пустил), а запись может быть ПРЕРВАНА (владелец сказал «стоп» или процесс
# кончился). Списки похожи, и кто-нибудь обязательно решит, что он один.
OUTCOMES = ("done", "partial", "failed", "cancelled")

# Исход, с которым запись рождается (см. шапку) и с которым закрывается
# запись, брошенная прошлым запуском.
BORN_OUTCOME = "failed"
ORPHAN_OUTCOME = "cancelled"

# Потолок на одну строку тела. Замер: самый толстый обычный промпт — около
# одиннадцати тысяч знаков, кириллицей это чуть больше двадцати килобайт.
# Тридцать два килобайта не обрежут ни один законный промпт, но удержат те
# четыре места, где обрезки нет вовсе.
MAX_PAYLOAD_BYTES = 32 * 1024

# Сколько дней живёт тело. Число — умолчание, а не закон: владелец правит его
# в настройках, не залезая в код. Этим же закрывается заранее описанный риск
# «записи раздувают базу»: реакция на него — уменьшить срок, а не править код.
DEFAULT_BODY_DAYS = 7
_DAYS_SETTING = "blackbox_body_days"

# Имя отметки «уборка за эти сутки уже прошла». Лежит в таблице счётчиков,
# ключ которой — сутки плюс имя. Таблица стоит пустая с блока 2 и заведена
# ровно под такие отметки; отдельного механизма «раз в сутки» в проекте нет.
_PURGE_MARK = "bb_purge"

# Своего замка нет — см. шапку. Запись идёт через кассу, она и стережёт
# очередь, и стережёт эту память.
_swept = False        # брошенные записи сметены (ровно один раз за запуск)
_purged_day = None    # за какие сутки уборка уже прошла в ЭТОМ процессе
_lost = 0             # сколько строк не удалось записать
_seq: dict = {}       # rec_id -> следующий номер строки в теле
_mine: set = set()    # записи, открытые ЭТИМ процессом


def lost_count() -> int:
    """Сколько строк записи потеряно. Не ноль — значит запись неполна."""
    return _lost


def reset_for_tests() -> None:
    """Забыть всё, что живёт на процесс. Зовёт tests/conftest.py.

    Защёлки «сметено» и «убрано за сутки» живут на запуск, а весь прогон —
    один запуск, поэтому первый же тест выключил бы их для всех следующих, и
    те были бы зелёными по неверной причине. Соединения здесь больше нет — им
    владеет касса, и сбрасывает его она сама.
    """
    global _swept, _purged_day, _lost, _seq, _mine
    _swept = False
    _purged_day = None
    _lost = 0
    _seq = {}
    _mine = set()


def _enabled() -> bool:
    """Пишем ли прямо сейчас.

    Под прогоном тестов без явно указанного дома — нет: восемьдесят файлов
    тестов не должны засорять запись владельца. Живой запуск — всегда да.
    Тот же порядок, что у журнала действий и журнала двери.
    """
    if os.environ.get("JARVIS_STATE_DIR", "").strip():
        return True
    return "pytest" not in sys.modules


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _ready() -> bool:
    """Есть ли в базе наши таблицы.

    Спрашивать можно только после того, как базу открыли хоть раз: до этого
    состояние схемы не заполнено. Открытие просим у кассы — она делает это
    вне замка записи, поэтому миграции и снимок дома никого не блокируют.
    """
    try:
        from core import store, writer
        writer.ensure_open()
        return bool(store.supports("blackbox"))
    except Exception:
        return False


def _body_days() -> int:
    """Сколько дней живёт тело. Число из настроек, умолчание — из плана."""
    try:
        from config.loader import get_setting
        got = get_setting(_DAYS_SETTING)
        if isinstance(got, int) and not isinstance(got, bool) and got >= 0:
            return got
    except Exception:
        pass
    return DEFAULT_BODY_DAYS


# -- Номер записи ---------------------------------------------------------

def rec_id_for(ctx=None) -> str:
    """Номер записи. Своего счётчика НЕТ нарочно.

    Номер строится от уже существующего уникального номера: от номера дела,
    если дело есть, иначе от номера запуска. Отсюда три следствия сразу: ни
    счётчика, ни гонки за него, ни миграции под него; «одна запись на запуск»
    обеспечена самим номером, а не дисциплиной; и по номеру записи сразу
    видно, к какому запуску или делу она относится.
    """
    from core import task_context
    got = task_context.current(ctx)
    task = getattr(got, "task_id", None)
    if task:
        return "B-" + str(task)
    return "B-" + str(getattr(got, "run_id", "?"))


# -- Заглушение и обрезка -------------------------------------------------

def _fingerprint(text: str) -> str:
    """Отпечаток ПОЛНОГО сырого текста — ключ, по которому ищет
    воспроизведение. Считается до обрезки и до заглушения (см. шапку)."""
    return hashlib.sha256(text.encode("utf-8", "replace")).hexdigest()


def _shrink(text: str):
    """Обрезать до потолка. Возвращает (текст, обрезали ли)."""
    data = text.encode("utf-8", "replace")
    if len(data) <= MAX_PAYLOAD_BYTES:
        return text, False
    return data[:MAX_PAYLOAD_BYTES].decode("utf-8", "ignore"), True


def _clean(text: str):
    """Заглушить секреты с проверкой. Возвращает (текст, получилось ли).

    Единственная точка вычистки на весь файл — в core/env. Своей регулярки
    здесь нет и быть не должно: два механизма об одном разойдутся, а план
    прямо требует одну точку. Не подтвердилось — наверх уйдёт «не получилось»,
    и текст не будет записан вовсе (fail-closed).
    """
    from core import env
    return env.redact_checked(text)


def _body_for(kind: str, payload) -> dict:
    """Собрать то, что ляжет в строку тела. Чистая работа, вне замка."""
    data = dict(payload or {})
    raw = data.get("t")
    out: dict = {}

    if kind == "prompt":
        text = "" if raw is None else str(raw)
        # Отпечаток и полную длину считаем ДО всего остального.
        out["h"] = _fingerprint(text)
        out["n"] = len(text)
        clean, ok = _clean(text)
        if not ok:
            # Вычистить не удалось — текста не будет, но дыра будет ВИДНА.
            out["hidden"] = True
            return out
        clean, cut = _shrink(clean)
        out["t"] = clean
        if cut:
            out["cut"] = True
        return out

    # Ответ модели. Отказ несёт КОД, а не рассказ: рассказ об ошибке — это
    # чужой текст, а он уже однажды приезжал наверх как просьба.
    out["ok"] = bool(data.get("ok"))
    if not out["ok"]:
        out["e"] = str(data.get("e") or "other")[:32]
        return out
    text = "" if raw is None else str(raw)
    clean, ok = _clean(text)
    if not ok:
        out["hidden"] = True
        return out
    clean, cut = _shrink(clean)
    out["t"] = clean
    if cut:
        # Обрезанный ответ воспроизводить НЕЛЬЗЯ: отдать обрубок за настоящий
        # ответ — значит соврать. Отметка нужна, чтобы отказаться громко.
        out["cut"] = True
    return out


# -- Открыть, дописать, закрыть -------------------------------------------

def open_rec(ctx=None, *, day: str, task_id=None):
    """Открыть запись (или вернуть уже открытую). Возвращает номер или None.

    Зовётся на КАЖДОМ вызове модели, поэтому обязана быть дешёвой: если
    запись этого процесса уже открыта, работы с базой не будет вовсе.

    `day` — сутки поставщика, полученные от учёта расхода (см. шапку). Этот
    файл их не вычисляет и не имеет права.
    """
    if not _enabled():
        return None
    rec = rec_id_for(ctx)
    if rec in _mine:
        return rec                      # быстрый путь: ни замка, ни базы
    if not _ready():
        return None
    from core import writer

    def job(conn):
        global _swept
        if rec in _mine:                # успели, пока мы шли к кассе
            return rec
        # СНАЧАЛА сметание брошенных: сейчас ни одной своей записи ещё нет,
        # значит всё открытое — из прошлой жизни. Позже так уже не рассудить.
        _sweep(conn)
        from core.state_version import CODE_VER
        conn.execute(
            "INSERT OR IGNORE INTO mx_bb_head (rec_id, task_id, "
            "code_ver, quota_day, outcome, created_utc) "
            "VALUES (?,?,?,?,?,?)",
            (rec, task_id, str(CODE_VER), str(day), BORN_OUTCOME, _now_iso()))
        _mine.add(rec)
        _seq.pop(rec, None)
        # Уборка — после того, как своя запись уже открыта: она пропускает
        # открытые, поэтому нашу не тронет.
        _purge_once(conn, day)
        return rec

    try:
        return writer.write(job, label="blackbox.open_rec")
    except Exception:
        _count_loss()
        return None


def write(rec_id, kind: str, payload) -> bool:
    """Дописать одну строку тела. Возвращает False вместо исключения — всегда.

    План описывает эту функцию как ничего не возвращающую. Отклонение
    осознанное: без ответа «легло или нет» правило «не смог вычистить — не
    пишем» проверить нечем, а сторожа обязаны его проверять.
    """
    if not rec_id or not _enabled():
        return False
    if kind not in KINDS:
        return False
    try:
        # Заглушение и обрезка — работа с текстом, а не с базой. Делается ДО
        # кассы нарочно: пока идёт запись, все остальные писатели стоят.
        body = _body_for(kind, payload)
        line = json.dumps(body, ensure_ascii=False, sort_keys=True,
                          separators=(",", ":"))
    except Exception:
        _count_loss()
        return False
    if not _ready():
        return False
    from core import writer

    def job(conn):
        seq = _next_seq(conn, str(rec_id))
        conn.execute(
            "INSERT INTO mx_bb_body (rec_id, seq, kind, payload, ts_utc) "
            "VALUES (?,?,?,?,?)",
            (str(rec_id), seq, str(kind), line, _now_iso()))
        _seq[str(rec_id)] = seq + 1
        return True

    try:
        return bool(writer.write(job, label="blackbox.write"))
    except Exception:
        _count_loss()
        return False


def close_rec(rec_id, outcome: str) -> bool:
    """Закрыть запись исходом. Здесь же в шапку кладётся число вызовов.

    Число считается ИЗ ТЕЛА и записывается в шапку именно сейчас, а не
    когда-нибудь потом. Причина простая: тело живёт считанные дни, а шапка
    вечно. Правило, по которому решается, что шапке хранить, одно — шапка
    хранит то, что переживёт свой источник.
    """
    if not rec_id or not _enabled():
        return False
    if outcome not in OUTCOMES:
        return False
    if not _ready():
        return False
    from core import writer

    def job(conn):
        _close_one(conn, str(rec_id), outcome)
        _mine.discard(str(rec_id))
        return True

    try:
        return bool(writer.write(job, label="blackbox.close_rec"))
    except Exception:
        _count_loss()
        return False


def _count_loss() -> None:
    global _lost
    _lost += 1


def _next_seq(conn, rec_id: str) -> int:
    """Следующий номер строки. Замок держит вызывающий.

    Первый раз за процесс спрашиваем базу, дальше считаем в памяти. Спросить
    обязательно: у записи, продолженной после перезапуска, строки уже есть, и
    счётчик с единицы налетел бы на первичный ключ.
    """
    known = _seq.get(rec_id)
    if known is not None:
        return known
    row = conn.execute("SELECT max(seq) FROM mx_bb_body WHERE rec_id=?",
                       (rec_id,)).fetchone()
    have = row[0] if row and row[0] is not None else 0
    return int(have) + 1


def _calls_in(conn, rec_id: str) -> int:
    """Сколько ответов модели легло в эту запись."""
    row = conn.execute(
        "SELECT count(*) FROM mx_bb_body WHERE rec_id=? AND kind=?",
        (rec_id, "model_out")).fetchone()
    return int(row[0]) if row else 0


def _close_one(conn, rec_id: str, outcome: str) -> None:
    """Закрыть одну запись. Транзакцию и замок держит вызывающий."""
    conn.execute(
        "UPDATE mx_bb_head SET outcome=?, closed_utc=?, calls_n=? "
        "WHERE rec_id=? AND closed_utc IS NULL",
        (outcome, _now_iso(), _calls_in(conn, rec_id), rec_id))


def _sweep(conn) -> int:
    """Закрыть записи, брошенные прошлым запуском. Ровно один раз за запуск.

    Зовётся только из open_rec, и только до того, как этот процесс открыл
    свою первую запись. В этот момент любая открытая запись — чужая, из
    прошлой жизни, и закрыть её как «прервано» честно: процесс кончился, а
    исхода никто не назвал.

    Своей транзакции нет: мы уже внутри записи, которую открыла касса.
    Второй `BEGIN` был бы ошибкой SQLite.
    """
    global _swept
    if _swept:
        return 0
    _swept = True
    rows = conn.execute(
        "SELECT rec_id FROM mx_bb_head WHERE closed_utc IS NULL").fetchall()
    for row in rows:
        _close_one(conn, str(row[0]), ORPHAN_OUTCOME)
    return len(rows)


# -- Уборка ---------------------------------------------------------------

def purge(*, conn=None, days=None, now_utc=None) -> int:
    """Убрать тела старше срока. Возвращает, сколько записей вычищено.

    Передали соединение — работаем на нём (так делают инструменты и тесты).
    Не передали — идём через кассу, как все.

    Три правила, и каждое куплено разбором, а не вкусом:

    1. ОТКРЫТЫЕ ЗАПИСИ НЕ ТРОГАЕМ. Иначе уборка однажды удалит середину
       живой задачи. Именно поэтому брошенные записи закрываются при старте —
       без этого их тела стали бы бессмертными.
    2. УДАЛЕНИЕ ТЕЛА И ФЛАГ — В ОДНОЙ ТРАНЗАКЦИИ. Держит именно ЭТО, а не
       порядок строк внутри: пока обе правки в одной транзакции, база либо
       примет их вместе, либо не примет ни одной, и порядок не значит ничего.
       Формулировку пришлось исправить: порча кода 19.08.2026 поменяла строки
       местами, и ни один тест не покраснел — потому что и не должен был.
       Но если кто-нибудь однажды РАЗНЕСЁТ их по двум транзакциям, тело
       обязано удаляться первым: флаг «убрано» при живом теле означал бы, что
       речь владельца стала бессмертной и невидимой одновременно.
    3. ШАПКА НЕ УДАЛЯЕТСЯ НИКОГДА. Она живёт вечно и потому не содержит ни
       одной колонки со свободным текстом. Цифры остаются, речь уходит.
    """
    from core import writer
    try:
        if conn is not None:
            # Соединение принесли своё (инструмент или тест). Транзакция всё
            # равно ОБЯЗАТЕЛЬНА: без неё удаление тела зафиксируется само, а
            # упавший следом флаг оставит тело удалённым при флаге «не убрано».
            # Поймано сторожом атомарности сразу после перевода на кассу
            # 19.08.2026 — первая версия перевода транзакцию потеряла.
            # Если мы уже внутри записи (так зовёт _purge_once), write_on
            # присоединится, а не начнёт вторую транзакцию.
            return writer.write_on(conn,
                                   lambda c: _purge_rows(c, days, now_utc))
        if not _ready():
            return 0
        return writer.write(lambda c: _purge_rows(c, days, now_utc),
                            label="blackbox.purge")
    except Exception:
        _count_loss()
        return 0


def _purge_rows(conn, days, now_utc) -> int:
    """Сама уборка. Транзакцию держит вызывающий (касса или инструмент)."""
    limit_days = _body_days() if days is None else int(days)
    moment = now_utc or datetime.now(timezone.utc)
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    edge = (moment - timedelta(days=limit_days)).isoformat(timespec="seconds")
    rows = conn.execute(
        "SELECT rec_id FROM mx_bb_head WHERE body_purged=0 "
        "AND closed_utc IS NOT NULL AND created_utc < ?", (edge,)).fetchall()
    for row in rows:
        rec = str(row[0])
        conn.execute("DELETE FROM mx_bb_body WHERE rec_id=?", (rec,))
        conn.execute(
            "UPDATE mx_bb_head SET body_purged=1 WHERE rec_id=?", (rec,))
    return len(rows)


def _purge_once(conn, day: str) -> int:
    """Уборка не чаще раза в сутки. Замок держит вызывающий.

    Отметка о запуске лежит в базе, а не только в памяти: иначе десять
    перезапусков за вечер дали бы десять уборок. Вставка отметки и есть
    заявка на право убирать — кто вставил, тот и убирает. Ключ таблицы
    отметок содержит сутки, поэтому назавтра право появится само.

    Сутки берутся те же, что у учёта расхода: третьего понятия «день» в
    проекте быть не должно.
    """
    global _purged_day
    if _purged_day == str(day):
        return 0
    _purged_day = str(day)
    try:
        cur = conn.execute(
            "INSERT OR IGNORE INTO mx_counter (quota_day, name, n) "
            "VALUES (?,?,1)", (str(day), _PURGE_MARK))
        if cur.rowcount != 1:
            return 0                      # за эти сутки уже убирал кто-то
    except Exception:
        return 0
    return purge(conn=conn)


