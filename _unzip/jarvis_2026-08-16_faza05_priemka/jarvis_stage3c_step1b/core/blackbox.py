def read_body(rec_id, *, conn=None) -> list:
    """Строки тела записи по порядку. Только чтение, ничего не меняет.

    Соединение не передали — берём СВОЁ, на чтение (Д41). Читать через кассу
    нельзя: чтение записи может быть длинным, а пока оно идёт, все писатели
    стояли бы.
    """
    if conn is None:
        try:
            from core import writer
            conn = writer.reader()
        except Exception:
            return []
    return _read_body_on(conn, rec_id)


def _read_body_on(conn, rec_id) -> list:
    try:
        rows = conn.execute(
            "SELECT seq, kind, payload, ts_utc FROM mx_bb_body "
            "WHERE rec_id=? ORDER BY seq", (str(rec_id),)).fetchall()
    except Exception:
        return []
    out = []
    for seq, kind, payload, ts in rows:
        try:
            body = json.loads(payload)
        except Exception:
            body = {}
        out.append({"seq": int(seq), "kind": str(kind), "body": body,
                    "ts_utc": str(ts)})
    return out


def read_heads(*, conn=None, limit: int = 20) -> list:
    """Последние шапки — то, что владелец увидит списком."""
    if conn is None:
        try:
            from core import writer
            conn = writer.reader()
        except Exception:
            return []
    try:
        rows = conn.execute(
            "SELECT rec_id, task_id, code_ver, quota_day, calls_n, outcome, "
            "body_purged, created_utc, closed_utc FROM mx_bb_head "
            "ORDER BY created_utc DESC LIMIT ?", (int(limit),)).fetchall()
    except Exception:
        return []
    return [dict(r) for r in rows if hasattr(r, "keys")]
