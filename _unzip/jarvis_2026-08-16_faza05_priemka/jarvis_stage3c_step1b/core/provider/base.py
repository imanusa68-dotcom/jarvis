# ЭТО НЕ core/provider_health.py. Тот сторожит поисковые движки (DDGS, Google
# CSE, SerpAPI) и про модели не знает ничего. Здесь наоборот: только модели и
# ни одного слова про поиск. Имена похожи, назначение разное.
#
# Зачем слой. До 09.08.2026 обращение к SDK жило внутри core/aux_model.py:
# создание клиента и сборка тела запроса стояли посреди логики квот, повторов
# и текстов отказа. Четырнадцать вызывающих мест из восьми файлов уже ходят
# через одну дверь core.aux_model.aux_call, но сама дверь была прибита к
# одному поставщику. Теперь SDK живёт ровно в одном файле проекта -
# core/provider/gemini.py.
#
# Весь договор поставщика - два метода, других обязанностей у него нет:
#
#   build_payload(prompt, image_parts) -> payload
#       Собрать тело запроса в форме, понятной только этому же поставщику.
#       Без картинки телом может быть просто строка. Тело непрозрачно: никто
#       кроме самого поставщика его не читает и не меняет. Собирает и
#       отправляет обязательно ОДИН И ТОТ ЖЕ экземпляр (см. get_provider).
#
#   generate(model, payload, api_key) -> str
#       Отправить и вернуть текст ответа. Пустой ответ - это "", не None.
#
# Чего поставщик НЕ делает - нарочно:
#   * не знает про остывание и 429 - это core/model_guard.py;
#   * не делает повторов и паузы - это core/aux_model.py, числа в реестре;
#   * не берёт ключ и не спрашивает имя модели - и то и другое ему передают;
#   * не печатает ни строчки - рот у проекта один, говорит вызывающий;
#   * НЕ ЛОВИТ И НЕ ОБОРАЧИВАЕТ ИСКЛЮЧЕНИЯ.
#
# Последний пункт - не вкус, а условие работы остывания. core/model_guard.py
# узнаёт исчерпание квоты по ТЕКСТУ исключения (иглы "429",
# "RESOURCE_EXHAUSTED", "quota"). Обёртка вида ProviderError("call failed")
# этот текст потеряет, и остывание молча перестанет включаться. Тесты такого
# не заметят: они бросают исключения сами, а не получают их от сети. Поэтому
# исключение уходит наверх ровно в том виде, в каком его дал SDK.
#
# Чего здесь СОЗНАТЕЛЬНО НЕТ: перевода чужих ошибок в общий вид (таксономии).
# Пока поставщик один, любая таксономия была бы догадкой - проверить её не на
# чем, второго ключа нет. Из этого следует честный вывод: слой даёт
# единственное место для SDK и точку подмены для тестов, но НЕ даёт
# переключаемости поставщика. Настоящая привязка живёт в разборе текста
# ошибок в core/model_guard.py; второй поставщик потребует сначала перенести
# этот разбор сюда.
#
# Живой голос и Screen View к этому слою не относятся и не должны быть в него
# затянуты. main.py, core/screen_live_runtime.py, core/screen_live_session.py,
# core/screen_share_manager.py и actions/screen_processor.py держат постоянную
# сессию по другому протоколу (WebSocket, а не разовый запрос). Их клиенты
# остаются на месте: сюда они не влезут, а попытка "дочистить" их этим слоем
# сломает голос.
# ---------------------------------------------------------------------------

from __future__ import annotations

from typing import Optional, Sequence, Tuple

# Картинки приходят так же, как их принимает aux_call: пары (байты, тип).
ImageParts = Optional[Sequence[Tuple[bytes, str]]]


class Provider:
    """Договор поставщика. Наследник обязан определить оба метода.

    Базовый класс нарочно не умеет ничего: попытка позвать его напрямую
    падает вслух с именем поставщика, а не возвращает пустой ответ, который
    вызывающий примет за неудачу модели.
    """

    #: Короткое имя для сообщений об ошибке. Не имя модели - имя поставщика.
    name = "base"

    def build_payload(self, prompt: str, image_parts: ImageParts = None):
        """Собрать тело запроса. Возврат непрозрачен для вызывающего."""
        raise NotImplementedError(
            "build_payload не определён у поставщика " + str(self.name)
        )

    def generate(self, model: str, payload, api_key: str) -> str:
        """Отправить тело и вернуть текст ответа. Ошибку не глотать."""
        raise NotImplementedError(
            "generate не определён у поставщика " + str(self.name)
        )
