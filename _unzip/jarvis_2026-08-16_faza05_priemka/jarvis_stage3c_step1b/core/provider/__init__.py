# Файл сделан по образцу core/awareness/__init__.py: только фасад, все тяжёлые
# импорты - внутри функций. Ввоз core.provider НЕ должен тянуть SDK: именно
# на этом держится прогон тестов без установленной зависимости и будущая
# проверка оффлайн-ядра (фаза 0.7).
#
# Поставщик ОДИН и общий на все потоки. Причина не в экономии: build_payload и
# generate обязаны попасть на ОДИН и тот же экземпляр, иначе тело запроса,
# собранное одним поставщиком, уедет в другого, который его не понимает.
# Агенты - потоки (флаг JARVIS_AGENTS), поэтому создание закрыто замком: без
# него два потока могли бы сделать двух поставщиков одновременно.
#
# Выбора поставщика через настройки ЗДЕСЬ НЕТ нарочно. Ключ один, сетевой
# проверки второго поставщика нет, а ключ в настройках без второго
# поставщика - это не гибкость, а ложное обещание и мёртвая ветка.
# ---------------------------------------------------------------------------

from __future__ import annotations

import threading

from core.provider.base import ImageParts, Provider  # noqa: F401

_LOCK = threading.Lock()
_PROVIDER = None


def get_provider() -> Provider:
    """Единственный поставщик вспомогательного пути.

    Импорт реализации ленивый: до первого запроса к модели файл с SDK не
    ввозится вообще.
    """
    global _PROVIDER
    if _PROVIDER is None:
        with _LOCK:
            if _PROVIDER is None:
                from core.provider.gemini import GeminiProvider
                _PROVIDER = GeminiProvider()
    return _PROVIDER


def set_provider(provider):
    """Подменить поставщика и вернуть прежнего - чтобы его можно было вернуть.

    Нужно только тестам и сторожам: на живой машине поставщика никто не
    меняет. Передать None - вернуться к настоящему при следующем запросе.
    """
    global _PROVIDER
    previous = _PROVIDER
    _PROVIDER = provider
    return previous
