# core/fences.py
"""
Заборы: чего агент не делает НИКОГДА, сколько бы его ни просили (фаза 1б-2).

Что охраняется и откуда это взято дословно
------------------------------------------
    I12 (дизайн-документ, строка 918): «Под-агенты не пишут в память и
        личность. Пишет только главный, через фильтр».
    Г-3 (план, строка 213): «что-либо -> память/личность/правила: пишет
        только главный по явной команде владельца; агенты — никогда (I12,
        I42). Память формирует будущее поведение; если её может править фон,
        поведение меняется незаметно».
    I12 про экран (план, строка 1023): «...а также vision без явного
        контекста».
    Х-P2 (план, строка 2795): «Просмотр экрана стоит дорого (vision) и легко
        съедает дневную квоту. Vision только по явному поводу, агентам без
        контекста — никогда».

ЗАМЕР, БЕЗ КОТОРОГО ЭТОГО ФАЙЛА НЕ БЫЛО БЫ СМЫСЛА ПИСАТЬ (28.08.2026)
--------------------------------------------------------------------
Прежде чем строить забор, я спросил дверь, что она сегодня пропускает
агенту (`mode="autonomous"`):

    save_memory      -> run       (риск low)  ПРОПУЩЕН
    screen_process   -> run       (риск low)  ПРОПУЩЕН
    file_controller  -> blocked   (риск high) отказ

То есть дыра настоящая, а не теоретическая: фоновая задача могла записать
владельцу в память что угодно и смотреть на его экран, и запись в журнале
выглядела бы совершенно законной («run, low»). Третья строка показывает, что
дверь в принципе умеет отказывать — значит дело не в двери, а в том, что для
этих двух инструментов правила не было вовсе.

ПОЧЕМУ НЕ ПРОСТО ПОДНЯТЬ РИСК В core/security.py
-------------------------------------------------
Соблазн: поставить `save_memory` риск high — и автономный путь отказал бы
сам, третьей строкой замера. Так делать НЕЛЬЗЯ, и это главное архитектурное
решение файла:

  * риск high означает «спросить владельца» и в РАЗГОВОРЕ тоже. Владелец
    говорит «запомни, что я не пью кофе после шести» — и вместо «Записал»
    услышал бы «Подтвердите». Это ломает то, ради чего память существует.
  * запрет агенту и вопрос владельцу — разные вещи. Смешав их в одном
    числе, мы теряем возможность сказать «ему никогда, а тебе сразу».

Поэтому забор — отдельная проверка, отвечающая на отдельный вопрос:
«кто просит», а не «насколько опасно».

ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ, И ЭТО НАРОЧНО
--------------------------------------
Он НЕ решает судьбу вызова. Он отвечает «есть препятствие или нет» и
объясняет причину словами. Решение принимает дверь (`core/gate.py`), потому
что в проекте одно место, где действие может быть запрещено (Г-2), и второго
быть не должно. Заведи забор своё «выполнять/не выполнять» — и на вопрос
«почему отказал» пришлось бы искать ответ в двух файлах.

ПОЧЕМУ РЕШАЕТ РОЛЬ, А НЕ РЕЖИМ
-------------------------------
Проверять `mode == "autonomous"` было бы короче на одну строку, но неверно.
Режим говорит «рядом ли человек», а забор охраняет «кто просит». Это
разъедется в первый же день фазы 2: главный агент может работать без
владельца у экрана (режим автономный), и запрещать ЕМУ запись в память
нельзя — I12 запрещает её под-агентам, а не всякой работе без человека.
Признак под-агента — заполненная роль в пропуске (`agent_role`), потому что
у разговора и у самой задачи она пуста, а появляется только у `.child()`.

Имён агентов здесь нет и быть не может: I21 — «ядро оркестратора не знает
имён конкретных агентов, никаких `if agent == "..."`». Поэтому забор смотрит
на факт наличия роли, а не на её значение.
"""
from __future__ import annotations

from typing import NamedTuple

# Инструменты, меняющие будущее поведение Джарвиса. Список ЗАКРЫТЫЙ и лежит
# кодом, а не в конфиге: I34 требует, чтобы состав таких перечней менялся
# осознанной правкой с новым тестом, а не «по ходу» и не файлом, который
# может подменить кто угодно.
#
# Почему здесь только `save_memory`, хотя память живёт в трёх файлах
# (long_term.json, personality.json, правила): остальные два сегодня не имеют
# инструмента, которым их можно записать — проверено грепом по политике
# (core/security.py, 24 инструмента). Записывать в список то, чего нет, —
# значит получить сторожа, который зелен, потому что проверять нечего.
# Когда инструмент появится, его добавят сюда вместе с тестом.
#
# ФАЗА 1Г: добавлен `forget_memory`. Причина — перекос, который забор фазы
# 1б-2 оставил открытым: под-агенту запретили ДОБАВЛЯТЬ факт, но не
# запретили его СТИРАТЬ, потому что `forget_memory` двери не спрашивал
# вовсе (его не было в политике, и дверь отвечала ему "Unknown tool").
# I12/Г-3 запрещает под-агентам «писать в память», и удаление — та же
# запись: факт исчез, будущее поведение Джарвиса поехало, причём
# незаметнее, чем от добавления. Запрет писать при разрешении удалять —
# не защита, а дырка в форме двери.
#
# `recall_memory` здесь СОЗНАТЕЛЬНО НЕТ — это решение владельца
# (28.08.2026, «да, я согласен» на таблицу доступа), а не недосмотр.
# Чтение будущего поведения не меняет и делает работу под-агента лучше:
# тому, кто ищет владельцу цену видеокарты, полезно знать, что владелец
# предпочитает NVIDIA. Закрыть чтение «на всякий случай» выглядит
# безопаснее, но платится качеством работы без выигрыша в защите.
#
# ФАЗА 1Е: добавлены `memory_self_write` и `personality_self_write` — поводы,
# под которыми ДОМ пишет сам, из фонового потока, никого не спросив. Без них
# запрет фазы 1г обходился в один шаг: под-агенту нельзя `save_memory`, но
# то же самое под именем дома прошло бы насквозь.
#
# И заодно закрыт перекос, честно описанный выше: комментарий гласил, что
# `personality.json` защищать нечем, потому что «инструмента, которым их
# можно записать», нет — «проверено грепом по политике». Инструмента правда
# не было. А ПИСАТЕЛЬ был: `main._update_memory_async` зовёт
# `update_personality()` напрямую. Он просто не инструмент, поэтому забор его
# не видел. Дыра была описана как «нечего защищать», хотя защищать было что —
# и это худшая половина: личность решает, КАК Джарвис говорит с владельцем.
#
# Замер (29.08.2026): в фоновом потоке `agent_role=None`, потому что
# contextvars через границу потока не переносится. То есть авто-запись всегда
# выглядит как владелец, и на роль здесь опираться нельзя — под-агент
# отличается только явно переданным пропуском.
MEMORY_TOOLS = frozenset({"save_memory", "forget_memory",
                          "memory_self_write", "personality_self_write"})

# Просмотр экрана и камеры. Отдельно от памяти, потому что причина другая:
# не «меняет поведение», а «дорого и подглядывает» (Х-P2, I12 про vision).
VISION_TOOLS = frozenset({"screen_process"})


class Fence(NamedTuple):
    """Ответ забора: препятствие есть или нет, и почему.

    `blocked` отдельным полем, а не «пустая причина значит можно»: пустую
    строку слишком легко получить случайно — из обрезки, из перевода, из
    несобранного f-шаблона. Признак и объяснение обязаны быть раздельными.
    """

    blocked: bool
    reason: str = ""
    message: str = ""


_OK = Fence(False)


def _role_of(ctx=None) -> str | None:
    """Роль просителя. Порядок старшинства — как во всём проекте.

    Явный пропуск сильнее контекста (правило 1 в шапке core/task_context),
    и полагаться только на параметр здесь нельзя по той же причине, что в
    двери: живые вызовы его не передают.

    Ошибка чтения пропуска НЕ означает «можно». Она означает «не знаю, кто
    просит», а на заборе незнание — это отказ (fail-closed): пропустить
    запись в память, не понимая, кто её просит, хуже, чем отказать лишний
    раз. Возвращаемое здесь `"unknown"` именно так и трактуется ниже.
    """
    try:
        from core import task_context
        return task_context.current(ctx).agent_role
    except Exception:
        return "unknown"


def check(tool: str, params: dict | None = None, *, ctx=None) -> Fence:
    """Есть ли забор на пути этого вызова.

    Возвращает `Fence(blocked=False)`, когда препятствий нет — то есть в
    подавляющем большинстве вызовов. Ни исключений, ни побочных действий:
    забор ничего не пишет и ничего не запускает, поэтому его можно спросить
    сколько угодно раз.
    """
    role = _role_of(ctx)

    # Роли нет — просит владелец через разговор или сама задача, поставленная
    # владельцем. Забор не про них: I12 запрещает запись ПОД-АГЕНТАМ.
    if role is None:
        return _OK

    name = str(tool or "")

    if name in MEMORY_TOOLS:
        # Причина и фраза различают запись и удаление. Раньше текст был
        # один («не пишет в память»), и на попытку под-агента СТЕРЕТЬ факт
        # владелец услышал бы «Это записывает в память» — про удаление, чего
        # он не просил. Формулировка, не совпадающая с действием, стоит
        # ровно столько же, сколько её отсутствие: по журналу нельзя понять,
        # что именно пытались сделать.
        erasing = name == "forget_memory"
        return Fence(
            True,
            reason=(f"I12/Г-3: под-агент ({role}) не стирает память"
                    if erasing else
                    f"I12/Г-3: под-агент ({role}) не пишет в память"),
            message=(
                "Это стирает факт из памяти, а такое делаю только я сам и "
                "только по вашей прямой просьбе, сэр. Скажите — забуду."
                if erasing else
                "Это записывает в память, а такое делаю только я сам и "
                "только по вашей прямой просьбе, сэр. Скажите — запишу."
            ),
        )

    if name in VISION_TOOLS:
        return Fence(
            True,
            reason=f"I12/Х-P2: под-агент ({role}) не смотрит на экран",
            message=(
                "Смотреть на экран в фоновой задаче я не буду, сэр: это "
                "дорого и без вас неуместно. Попросите прямо — посмотрю."
            ),
        )

    return _OK
