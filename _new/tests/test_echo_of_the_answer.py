"""Сторожа на эхо ответа — фраза, сказанная владельцу ДВАЖДЫ.

ОТКУДА ВЗЯЛИСЬ ЭТИ ТЕСТЫ
Прогон владельца на Windows 28.08.2026. Он сказал «запомни, мне нравится
меренговый торт» и услышал ответ ДВА РАЗА подряд, слово в слово, с паузой
меньше секунды. В окне это выглядело одной строкой с удвоенным текстом.

ПОЧЕМУ ЭТИ ТЕСТЫ ПОЯВИЛИСЬ ТОЛЬКО СЕЙЧАС — ЧЕСТНО
Речевой путь (`out_buf`, `output_transcription`, вывод в окно) не был
покрыт НИ ОДНИМ тестом: `grep -rln out_buf tests/` возвращал пусто. То
есть сборку фразы из кусочков можно было сломать и не узнать об этом до
следующего живого разговора. Дефект нашёл владелец ушами — это и есть цена
непокрытого пути.

ЧТО ИМЕННО СТЕРЕГУТ ЭТИ ТЕСТЫ
Не «модель больше не удваивает» — этим управляет сервер Google, и мы на
него влиять не можем. Стерегут ДВЕ вещи, которые в нашей власти:
  1. распознавание эха работает и не трогает живую речь;
  2. наш код по-прежнему печатает фразу ОДИН раз за ход и складывает
     кусочки в правильном порядке — то есть удвоение точно приходит
     снаружи, а не рождается у нас.
"""
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.echo_guard import MIN_ECHO_CHARS, describe, looks_doubled, split_echo

# Настоящая фраза из прогона владельца. Не выдуманный пример: если сторож
# зелёный на синтетике и красный на реальности — он бесполезен.
REAL = "Конечно, сэр. Я запомнил, что вам нравится меренговый торт."


# ── 1. Распознавание известного дефекта ──────────────────────────────────────

@pytest.mark.parametrize("glue", ["", " ", "  ", "   "])
def test_the_owners_doubled_answer_is_recognised(glue):
    """Фраза владельца, склеенная как угодно, распознаётся как эхо.

    Вариантов склейки несколько, потому что расшифровка приходит кусками и
    `" ".join(...)` в main.py легко даёт лишние пробелы на границе. Сторож,
    который ловит только один вариант склейки, промахнётся на живой машине.
    """
    single, doubled = split_echo(REAL + glue + REAL)
    assert doubled, f"эхо не распознано при склейке {glue!r}"
    assert single == REAL, (
        "эхо распознано, но фраза восстановлена неверно — "
        f"получено {single!r}")


def test_the_warning_says_data_is_intact():
    """Предупреждение обязано сказать, что запись НЕ удвоилась.

    Иначе владелец, увидев «озвучено дважды», решит что и в память легло
    два факта — и пойдёт чистить память, которая в порядке. Измерено:
    инструмент вызывается один раз, в журнале одна строка.
    """
    msg = describe(REAL + " " + REAL)
    assert msg, "предупреждение пустое — дефект останется невидимым"
    assert "данные целы" in msg, (
        "в предупреждении нет слов о целости данных — владелец решит, "
        "что память тоже удвоилась")
    assert "дважды" in msg.lower()


def test_a_single_answer_raises_no_warning():
    """Обычный ответ не должен ничего печатать.

    Сторож против шума: предупреждение, которое появляется постоянно,
    перестают читать — и настоящее пропускают.
    """
    assert not looks_doubled(REAL)
    assert describe(REAL) == ""


# ── 2. Живую речь не портим ──────────────────────────────────────────────────

@pytest.mark.parametrize("text", [
    "Да. Да.",                              # согласие голосом
    "Хорошо, хорошо",                       # живая интонация
    "Хорошо, сэр. Хорошо, сэр, уже делаю.",  # законный повтор внутри фразы
    "Так-так",
    "",
    "   ",
])
def test_living_speech_is_never_called_an_echo(text):
    """Короткие и законные повторы — это НЕ дефект.

    Порог MIN_ECHO_CHARS существует ровно для этого. Если сторож начнёт
    считать «Да. Да.» сбоем, предупреждение будет сыпаться в каждом
    разговоре, и его перестанут замечать.
    """
    assert not looks_doubled(text), f"живая речь принята за эхо: {text!r}"


def test_none_does_not_crash_the_recv_loop():
    """None не должен ронять цикл приёма.

    Проверка не теоретическая: диагностика зовётся из `_recv_loop`, а
    падение там убивает сессию целиком — Джарвис замолчит. Диагностика
    НИКОГДА не имеет права быть опаснее того, что она диагностирует.
    """
    assert split_echo(None) == ("", False)
    assert describe(None) == ""


def test_three_repeats_are_not_our_case():
    """Тройной повтор намеренно НЕ ловится.

    Наблюдён ровно двойной. Расширять правило «на всякий случай» — значит
    угадывать; жадный поиск любых повторов начнёт срезать законную речь.
    Когда/если увидим тройной — добавим по факту, а не по фантазии.
    """
    assert not looks_doubled(REAL + " " + REAL + " " + REAL)


def test_the_threshold_is_documented_and_sane():
    """Порог не должен уползти в бессмыслицу при «улучшении».

    При пороге 0 сторож объявит эхом любое «а а», при пороге 200 — не
    поймает даже реальную фразу владельца (она 59 символов).
    """
    assert 5 <= MIN_ECHO_CHARS <= 40
    assert len(REAL) > MIN_ECHO_CHARS


# ── 3. Наш код печатает фразу ОДИН раз — значит дубль приходит снаружи ───────

def _replay(events):
    """Повтор логики main.py:1797-1846 (сборка расшифровки и вывод).

    ЗАЧЕМ КОПИЯ, А НЕ ВЫЗОВ НАСТОЯЩЕГО ЦИКЛА: `_recv_loop` требует живой
    сессии, микрофона и ключа — ничего этого в тестах нет. Копия узкая и
    сверяется с оригиналом следующим тестом, чтобы не разъехаться молча.
    """
    out_buf, lines = [], []
    for kind, payload in events:
        if kind == "chunk":
            txt = (payload or "").strip()
            if txt:
                out_buf.append(txt)
        elif kind == "turn_complete":
            full = " ".join(out_buf).strip()
            if full:
                lines.append(f"Jarvis: {full}")
            out_buf = []
    return lines


def test_our_code_prints_the_answer_once_per_turn():
    """Кусочки одной фразы дают РОВНО одну строку в окне."""
    lines = _replay([
        ("chunk", "Конечно, сэр."),
        ("chunk", "Я запомнил, что вам"),
        ("chunk", "нравится меренговый торт."),
        ("turn_complete", None),
    ])
    assert lines == ["Jarvis: Конечно, сэр. Я запомнил, что вам нравится "
                     "меренговый торт."], lines


def test_the_double_comes_from_outside_not_from_us():
    """Удвоение в окне возникает ТОЛЬКО если сервер прислал текст дважды.

    Это ключевой тест диагноза. Он показывает: наш код не размножает
    фразу — он честно печатает то, что пришло. Значит правка фазы 1в
    (и любая другая наша правка в _execute_tool) к удвоению отношения не
    имеет, и искать надо на стороне модели.
    """
    once = _replay([("chunk", REAL), ("turn_complete", None)])
    assert len(once) == 1
    assert not looks_doubled(once[0])

    twice = _replay([("chunk", REAL), ("chunk", REAL), ("turn_complete", None)])
    assert len(twice) == 1, "две строки вместо одной — сборка хода сломана"
    assert looks_doubled(twice[0].removeprefix("Jarvis: ")), (
        "сервер прислал фразу дважды, а сторож эха этого не заметил")


def test_the_buffer_is_emptied_between_turns():
    """Буфер обязан очищаться, иначе прошлый ответ приклеится к следующему.

    Без очистки Джарвис на второй вопрос ответил бы «старый ответ + новый»
    — и это выглядело бы точно как эхо, но причина была бы НАША. Тест
    закрывает эту версию: очистка на месте.
    """
    lines = _replay([
        ("chunk", "Первый ответ, достаточно длинный."),
        ("turn_complete", None),
        ("chunk", "Второй ответ, тоже длинный."),
        ("turn_complete", None),
    ])
    assert lines == ["Jarvis: Первый ответ, достаточно длинный.",
                     "Jarvis: Второй ответ, тоже длинный."], lines
    assert "Первый" not in lines[1], (
        "прошлый ответ протёк в следующий ход — буфер не очищается")


def test_the_model_is_told_not_to_speak_twice():
    """В описании save_memory есть прямой запрет говорить второй раз.

    Это единственное средство, которое может СНИЗИТЬ частоту дефекта:
    протокол запретить второй ответ не умеет (scheduling=SILENT действует
    только для NON_BLOCKING, а перевод туда воспроизводит удвоение —
    проверено разработчиками Google 07.01.2026). Инструкция — просьба, не
    гарантия, поэтому и живёт рядом с диагностикой, а не вместо неё.

    Сторож нужен потому, что описание инструмента — длинный текст, из
    которого при «сокращении» легко выпадет одна фраза, и никто не заметит,
    пока владелец снова не услышит повтор.
    """
    import main  # noqa: PLC0415 — импорт внутри: main тянет звук и окна

    decl = next(d for d in main.TOOL_DECLARATIONS
                if d["name"] == "save_memory")
    text = decl["description"].lower()
    assert "do not speak again" in text, (
        "из описания save_memory исчез запрет говорить второй раз — "
        "вернётся удвоенный ответ, который владелец слышал 28.08.2026")
    assert "one reply per turn" in text


def test_the_replay_still_matches_main_py():
    """Копия логики выше не разъехалась с main.py.

    Сторож против самой опасной болезни копий: оригинал поправили, копия
    осталась старой, тесты зелёные, а проверяют вымысел. Проверяются
    именно те четыре строки, на которых держится вывод фразы.
    """
    src = (ROOT / "main.py").read_text(encoding="utf-8")
    body = src[src.index("out_buf: list[str] = []"):]
    body = body[:body.index("# ── Tool calls")]

    for needle in ("out_buf.append(txt)",
                   'full_out = " ".join(out_buf).strip()',
                   'self.ui.write_log(f"Jarvis: {full_out}")',
                   "out_buf = []"):
        assert needle in body, (
            f"main.py больше не содержит {needle!r} — копия логики в этом "
            "тесте устарела, проверять её бессмысленно")
