# -*- coding: utf-8 -*-
"""Сторожа на ВТОРОЙ вид «отвечает два раза» — две РАЗНЫЕ реплики в одном ходу.

ОТКУДА ЭТО ВЗЯЛОСЬ
Владелец 29.08.2026: «мне реально бесит», ответ дважды. Сторож эха
(`core/echo_guard.split_echo`) при этом молчал, и это было не случайностью:
он ловит только ДОСЛОВНЫЙ дубль — тот, что был 28.08 с меренговым тортом.

Исследование (зонды 39-40) разделило жалобу на два несвязанных дефекта:

  СЛУЧАЙ 1 — серверный дубль, слово в слово. Не наш: звук генерирует сервер
  Google, документировано в шапке `core/echo_guard.py`.

  СЛУЧАЙ 2 — ответ по существу ДО вызова инструмента и доклад о записи
  ПОСЛЕ него. Слова разные, поэтому `looks_doubled` даёт False. Для уха это
  тот же двойной ответ. Замер по журналу 29.08: 3 хода из 3, где звался
  инструмент.

ПОЧЕМУ СЛУЧАЙ 2 — НАШ, А НЕ ГУГЛОВСКИЙ
Его прямо заказывал наш промпт: 7 правил вида «just call it, then report»
против НУЛЯ исключений для тихих инструментов памяти (замерено зондом 40).
Модель слушалась: говорила ответ, звала `save_memory`, потом докладывала.

ЧТО СТЕРЕГУТ ЭТИ ТЕСТЫ
Не «модель больше так не делает» — это решает модель. Стерегут две вещи в
нашей власти:
  1. ПРИБОР: граница «до вызова / после вызова» больше не выбрасывается, и
     вторая реплика видна в терминале;
  2. ПРАВИЛО: в промпте есть исключение «один ответ за ход», и его нельзя
     удалить молча.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.echo_guard import describe_split_turn, looks_doubled

MAIN = (ROOT / "main.py").read_text(encoding="utf-8")
BEHAVIOR = (ROOT / "core" / "prompts" / "06_behavior.txt").read_text(
    encoding="utf-8", errors="replace"
)
# Промпт свёрстан по ~80 знаков, и любая проверяемая фраза может оказаться
# разорванной переносом («For a slow\n    tool»). Первая версия теста ниже
# именно на это и упала: искала "slow tool" и не находила, хотя правило
# стояло на месте. Сторож, чувствительный к вёрстке, а не к смыслу, гарантирует
# ложную тревогу при первом же переформатировании — поэтому сверяем по тексту
# со сведёнными пробелами.
BEHAVIOR_FLAT = re.sub(r"\s+", " ", BEHAVIOR)


# ── 1. Прибор различает то, чего не различал старый сторож ───────────────────

def test_the_real_case_from_the_owners_log_is_now_visible():
    """Настоящий ход владельца 29.08: две реплики, разные слова.

    Это тот самый случай, который старый сторож пропускал. Если он снова
    станет невидимым — тест краснеет.
    """
    before = "Ваш кот, Тигр, видимо, ищет тепла."
    after = "Отмечено, сэр: Тигр орёт под дверью."
    assert not looks_doubled(f"{before} {after}"), (
        "старый сторож не должен видеть здесь дубль — иначе тест проверяет "
        "не то, что задумано"
    )
    warn = describe_split_turn(before, after)
    assert warn, "вторая реплика в одном ходу осталась невидимой"
    assert "две реплики" in warn


def test_a_clean_turn_stays_silent():
    """Модель промолчала, вызвала инструмент, ответила один раз — НЕ дефект.

    Это самый частый правильный ход. Сторож, который ругается на него,
    владелец выключит в первый же день, и вместе с ним пропадёт диагностика
    настоящего дефекта.
    """
    assert describe_split_turn("", "Ваш кот, Тигр, видимо, ищет тепла.") == ""


def test_speaking_only_before_the_tool_is_also_clean():
    """Сказал до вызова и замолчал после — тоже правильный ход."""
    assert describe_split_turn("Секунду, сэр.", "") == ""


def test_a_short_report_after_the_tool_is_not_excused_by_being_short():
    """«Готово, сэр» — ровно тот лишний доклад, а не мелочь.

    Порога длины здесь нет намеренно: признак структурный, а не текстовый.
    Отсев по длине спрятал бы самый частый вид дефекта.
    """
    warn = describe_split_turn("Ваш кот ищет тепла.", "Готово, сэр.")
    assert warn, "короткий доклад после инструмента обязан быть виден"


def test_the_wording_says_whether_words_matched():
    """Дословный повтор и «другими словами» — разные диагнозы.

    Первый лечится только на стороне Google, второй — нашим промптом.
    Если прибор их не различает, владелец не поймёт, чья это поломка.
    """
    same = describe_split_turn("Кот ищет тепла.", "Кот ищет тепла.")
    other = describe_split_turn("Кот ищет тепла.", "Отмечено, сэр.")
    assert "дословно то же" in same
    assert "другими словами" in other


# ── 2. Граница хода действительно сохраняется в main.py ──────────────────────

def test_main_marks_the_boundary_at_the_tool_call():
    """Отметка ставится в блоке tool_call, иначе граница снова потеряется."""
    assert "said_before_tool" in MAIN, "отметка границы исчезла из main.py"
    i = MAIN.index("if response.tool_call")
    block = MAIN[i: i + 700]
    assert "said_before_tool = len(out_buf)" in block, (
        "отметка больше не ставится при вызове инструмента"
    )


def test_the_boundary_is_marked_only_once_per_turn():
    """Два вызова подряд не должны сдвигать отметку.

    Без этой проверки вторая отметка съела бы реплику, сказанную между
    вызовами, и дефект стал бы невидимым именно в самом сложном случае.
    """
    i = MAIN.index("if response.tool_call")
    block = MAIN[i: i + 700]
    assert "if said_before_tool < 0" in block, (
        "пропала защита от повторной отметки при нескольких вызовах"
    )


def test_the_boundary_is_reset_after_every_turn():
    """Без сброса отметка от прошлого хода испортит следующий."""
    assert "said_before_tool = -1" in MAIN, "отметка не сбрасывается"
    assert MAIN.count("said_before_tool = -1") >= 2, (
        "сброс должен быть и на входе в цикл, и после turn_complete"
    )


def test_the_diagnostic_cannot_kill_the_session():
    """Проверка живёт внутри цикла приёма: падение здесь = Джарвис замолчал.

    То же правило, что и у старого сторожа эха: диагностика не имеет права
    быть опаснее того, что она диагностирует.
    """
    # Окно берём от РЕАЛЬНОГО начала блока, а не «плюс-минус 400 знаков»:
    # первая версия теста упала именно из-за размера окна — объяснение
    # дефекта в комментарии оказалось длиннее, чем окно, и `try:` в него не
    # попал. Сторож, зависящий от длины комментария, бесполезен.
    i = MAIN.index("describe_split_turn as _split")
    head = MAIN.rfind("try:", 0, i)
    tail = MAIN.find("except Exception:", i)
    assert head != -1 and tail != -1, "вызов диагностики не обёрнут в try/except"
    assert 0 < i - head < 900, (
        "ближайший try: слишком далеко — диагностика, скорее всего, "
        "оказалась вне защиты")


def test_the_two_echo_checks_stay_independent():
    """Старый сторож дубля не должен быть заменён новым.

    Дефекты разные, и лечение у них разное. Потеря любого из двух приборов
    вернёт нас к «слышу два раза, а в терминале тихо».
    """
    assert "from core.echo_guard import describe as _echo" in MAIN
    assert "describe_split_turn" in MAIN


# ── 3. Правило в промпте, которое заказывало вторую реплику ──────────────────

def test_the_prompt_now_forbids_two_replies_in_one_turn():
    assert "ONE ANSWER PER TURN" in BEHAVIOR_FLAT, (
        "исключение «один ответ за ход» пропало из промпта — правило "
        "«then report» снова заказывает вторую реплику"
    )


def test_the_exception_names_the_silent_memory_tools():
    """Общего запрета мало: дефект приходил именно на инструментах памяти.

    Их ответ (`{'result': 'ok', 'silent': True}`) докладывать не о чем, но
    правило «then report» не делало для них исключения — замерено зондом 40:
    7 правил «скажи после», 0 исключений.
    """
    low = BEHAVIOR_FLAT.lower()
    assert "save_memory" in low and "forget_memory" in low
    i = low.index("one answer per turn")
    block = low[i: i + 900]
    assert "save_memory" in block, (
        "исключение не упоминает save_memory — именно на нём дефект и жил"
    )


def test_the_rule_forbids_the_report_wording_the_owner_heard():
    """«Отмечено, сэр» — расписка, а не ответ. Пример обязан остаться.

    Пример нужен потому, что запрет без образца модель обходит: она считает
    доклад «естественным ответом», как её и просили выше.
    """
    i = BEHAVIOR_FLAT.lower().index("one answer per turn")
    block = BEHAVIOR_FLAT[i: i + 900].lower()
    assert "noted, sir" in block, "пропал образец лишнего доклада"
    assert "two" in block, "не сказано, что это считается ДВУМЯ ответами"


def test_the_rule_does_not_contradict_the_slow_tool_rule():
    """Медленным инструментам речь ДО вызова по-прежнему нужна.

    Иначе владелец получит тишину на 30 секунд поиска — это была бы замена
    одного дефекта другим, худшим.
    """
    i = BEHAVIOR_FLAT.lower().index("one answer per turn")
    block = BEHAVIOR_FLAT[i: i + 900].lower()
    assert "slow tool" in block, (
        "правило не оговаривает медленные инструменты и потому запрещает "
        "нужную реплику перед долгим ожиданием"
    )
