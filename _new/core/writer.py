# core/writer.py
"""
Одна касса записи в базу (фаза 1, блок 7). Решение Д41, факт Ф11.

ЗАЧЕМ ЭТОТ ФАЙЛ, И ЧЕГО ОН НЕ ДЕЛАЕТ
------------------------------------
Замерено 19.08.2026, и это надо сказать честно: потери записи ВНУТРИ Джарвиса
сегодня нет. Чтобы одна транзакция задержала соседа дольше терпения SQLite
(5 с), в ней должно быть около семидесяти тысяч строк; самая частая запись в
проекте — две строки на вызов модели. WAL и терпение уже выстраивают писателей
в очередь.

Значит касса — не ремонт, а страховка, и ставится она под две настоящие
вещи, а не под выдуманную:

  1. БЛОК 8. Появятся потоки-агенты, которые пишут задачи одновременно. Ф11
     плана говорит дословно: «сериализации записи между потоками в коде нет:
     её надо добавить (единый замок записи)». Сегодня в core/store.py нет ни
     одного замка — проверено.
  2. ЧУЖОЙ ПРОЦЕСС. Замерено: процесс, держащий запись 7 секунд (доктор,
     откат, воспроизведение), роняет нашу запись с «database is locked» через
     5,68 с. Внутренний замок от этого не спасает вообще — спасает ПОВТОР, и
     касса единственное место, где его можно завести один раз на всех.

ПОЧЕМУ ЗАМОК, А НЕ ПОТОК-ПИСАТЕЛЬ
---------------------------------
Д41 просит «один поток-писатель», но более свежий текст того же плана (Ф11)
просит «единый замок записи». План противоречит себе, и выбран замок:

  * вложенная запись. `consent_store.consume(on_authorized=...)` вызывает
    чужую функцию ИЗНУТРИ записи, и та сама пишет в базу. С очередью такой
    вызов ждал бы собственной очереди — то есть навсегда;
  * ошибка. Через замок она возвращается звонящему обычным исключением, а
    через очередь её надо переносить между потоками руками;
  * новый вид отказа. Умерший поток-писатель означает, что НИЧЕГО больше не
    пишется, и узнать об этом негде;
  * цена. Замерено на одинаковой работе: 0,20 мс против 0,19 мс.

Джарвис — один процесс (это стережёт файловый замок), дочерних процессов с
базой нет вовсе. Значит внутрипроцессной сериализации достаточно.

ПЯТЬ ПРАВИЛ, КАЖДОЕ КУПЛЕНО ЗАМЕРОМ ИЛИ РАЗБОРОМ
------------------------------------------------
1. `BEGIN IMMEDIATE`, а не `DEFERRED`. Немедленный берёт замок базы СРАЗУ,
   поэтому повторять надо только его: если он прошёл, до конца транзакции
   никто не вмешается. Это делает повтор безопасным без всяких условий —
   не нужно требовать, чтобы работа была повторяемой. С отложенным замок
   брался бы на первой записи, посреди работы, и повтор пришлось бы делать
   с половины.

2. ВЛОЖЕННАЯ ЗАПИСЬ ПРИСОЕДИНЯЕТСЯ к открытой транзакции. Не RLock: он спас
   бы от зависания, но родил бы вторую беду — вложенный вызов закрыл бы
   транзакцию раньше внешней, и внешняя работа осталась бы без отката.
   Проверено прототипом до написания этого файла.

3. СОЕДИНЕНИЕ СОЗДАЁТСЯ ВНЕ ЗАМКА ЗАПИСИ. Открытие базы умеет запустить
   миграции и снять копию всего дома; под замком это был бы самозахват.
   Для создания есть отдельный маленький замок, который НИКОГДА не держится
   во время работы с базой.

4. ЗАМОК КАССЫ — ЕДИНСТВЕННЫЙ, КОТОРЫЙ СТЕРЕЖЁТ ЗАПИСЬ. Замки модулей,
   существовавшие ради этого, снимаются, а не остаются рядом. Иначе появился
   бы РАЗНЫЙ ПОРЯДОК захвата, а это готовая мёртвая хватка: поток А держит
   кассу и ждёт замок модуля, поток Б наоборот. Живьём это выглядит как
   «Джарвис завис при запуске», и искать будут в микрофоне.

5. ЧТЕНИЕ — СВОЁ СОЕДИНЕНИЕ НА ПОТОК, только чтение (так требует Д41).
   Тяжёлое чтение (поиск по памяти — по замеру в самом файле памяти до 2,5 с
   на десяти тысячах фактов) не имеет права стоять за записью.

ЧТО ЗАПРЕЩЕНО ДЕЛАТЬ ВНУТРИ `write`
-----------------------------------
Работа под кассой обязана быть ТОЛЬКО РАБОТОЙ С БАЗОЙ. Никакой сети, никакого
ожидания другого замка, никакой печати. Причина простая: пока работа идёт, все
остальные писатели стоят. Сеть под кассой — это зависший Джарвис.
"""
from __future__ import annotations

import os
import sqlite3
import sys
import threading
import time
from contextlib import contextmanager
from pathlib import Path

# Сколько раз пробовать взять замок базы. Каждая попытка сама ждёт до 5 с
# (это терпение задано при открытии соединения), поэтому три попытки — это
# около пятнадцати секунд в худшем случае. Число выбрано замером: чужой
# процесс, державший запись 7 секунд, побеждается ОДНИМ повтором.
BEGIN_ATTEMPTS = 3
BEGIN_PAUSE_S = 0.2

_LOCK = threading.Lock()        # единственный замок записи
_NEW_CONN_LOCK = threading.Lock()   # только создание соединения, не работа

_conn = None
_conn_path = None
_depth = threading.local()      # уже внутри записи в ЭТОМ потоке?
_readers = threading.local()    # своё соединение на чтение

_stats = {"writes": 0, "nested": 0, "retries": 0, "failures": 0}


class WriteBusy(RuntimeError):
    """База занята дольше, чем мы согласны ждать. Наверх летит как есть.

    Молчаливо терять запись нельзя: звонящий сам решит, можно ли пережить
    потерю (чёрному ящику можно, талону согласия — нет).
    """


def stats() -> dict:
    """Сколько записей прошло, сколько было повторов и отказов."""
    return dict(_stats)


def _drop() -> None:
    """Закрыть соединение записи. Замок создания держит вызывающий."""
    global _conn, _conn_path
    try:
        if _conn is not None:
            _conn.close()
    except Exception:
        pass
    _conn = None
    _conn_path = None


def reset_for_tests() -> None:
    """Забыть соединения и числа. Зовёт tests/conftest.py.

    Соединение помнит ПРОШЛЫЙ дом, а каждый тест получает свой — без сброса
    тест писал бы в чужую базу. Та же болезнь и тот же рецепт, что у
    остальных восьми пунктов списка в conftest.
    """
    global _readers
    with _NEW_CONN_LOCK:
        _drop()
    _readers = threading.local()
    for key in _stats:
        _stats[key] = 0
    _depth.n = 0


def _connection():
    """Соединение записи. Берётся ВНЕ замка записи — см. правило 3.

    Путь сверяется при каждом обращении: тест меняет дом на ходу, и
    соединение к прошлому дому писало бы не туда.
    """
    global _conn, _conn_path
    from core import store
    path = str(store.db_path())
    if _conn is not None and _conn_path == path:
        return _conn
    with _NEW_CONN_LOCK:
        if _conn is not None and _conn_path == path:
            return _conn
        _drop()
        conn = store.open_store()
        _conn = conn
        _conn_path = path
        return conn


def _begin(conn) -> None:
    """Взять замок базы. Повтор — только здесь, и это безопасно (правило 1)."""
    last = None
    for attempt in range(1, BEGIN_ATTEMPTS + 1):
        try:
            conn.execute("BEGIN IMMEDIATE")
            return
        except sqlite3.OperationalError as exc:
            last = exc
            _stats["retries"] += 1
            if attempt < BEGIN_ATTEMPTS:
                time.sleep(BEGIN_PAUSE_S * attempt)
    _stats["failures"] += 1
    raise WriteBusy(f"база занята: {last}")


@contextmanager
def transaction(conn=None):
    """Касса как контекст: `with transaction() as conn: ...`.

    ЭТО ЕДИНСТВЕННЫЙ МЕХАНИЗМ на весь файл. `write` и `write_on` — только две
    формы вызова поверх него. Две независимые реализации одного и того же
    рано или поздно расходятся, и тогда встаёт вопрос «какая из них сегодня
    правда» — проект уже дважды за это платил.

    Соединение не передали — берём своё и встаём в очередь.
    Передали НАШЕ же — то же самое: очередь всё равно нужна.
    Передали ЧУЖОЕ — работаем на нём без очереди: так делают инструменты
    (это отдельные процессы, наш замок им не виден, их сериализует SQLite),
    миграции (идут до того, как касса может работать) и тесты.
    """
    own = conn if conn is not None else _connection()
    mine = own is _conn

    if getattr(_depth, "n", 0):
        # Уже внутри записи в этом потоке: присоединяемся к открытой
        # транзакции, а не начинаем свою (правило 2).
        _stats["nested"] += 1
        yield own
        return

    if mine:
        _LOCK.acquire()
    try:
        _begin(own)
        _depth.n = 1
        try:
            yield own
            own.execute("COMMIT")
            _stats["writes"] += 1
        except Exception:
            try:
                own.execute("ROLLBACK")
            except Exception:
                pass
            raise
        finally:
            _depth.n = 0
    finally:
        if mine:
            _LOCK.release()


def write(fn, *, label: str | None = None):
    """Выполнить fn(conn) в транзакции. Все писатели идут здесь по очереди.

    Возвращает то, что вернула fn. Исключение из fn откатывает транзакцию и
    уходит наверх: касса ничего не глотает, решение «пережить потерю или
    нет» принимает звонящий.

    `label` — только для отладки, в базу не попадает.
    """
    with transaction() as conn:
        return fn(conn)


def in_write() -> bool:
    """Идёт ли запись в этом потоке прямо сейчас. Нужно сторожам."""
    return bool(getattr(_depth, "n", 0))


def ensure_open() -> None:
    """Открыть базу (и поднять схему), не начиная записи.

    Нужно тем, кто перед записью спрашивает «а есть ли моя таблица»: ответ на
    этот вопрос появляется только после того, как базу открыли хоть раз.
    Открытие идёт вне замка записи, как и всегда.
    """
    _connection()


def conn():
    """Соединение записи для тех, кто держит долгоживущий объект над базой.

    Так устроен журнал: он получает соединение один раз в конструктор и живёт
    с ним весь процесс. Отдать ему соединение кассы — единственный способ
    сделать его записи частью общей очереди, не переписывая все четырнадцать
    его методов.
    """
    return _connection()


def write_on(conn_, fn):
    """Транзакция на принесённом соединении. Форма вызова поверх transaction."""
    with transaction(conn_) as c:
        return fn(c)


# -- Чтение ---------------------------------------------------------------

def reader():
    """Своё соединение на поток, ТОЛЬКО ЧТЕНИЕ (правило 5).

    Открывается в режиме «только чтение», чтобы случайная запись отсюда
    падала вслух, а не проходила мимо кассы. Если путь не лезет в адрес
    (пробелы, кириллица, решётка в имени папки — у владельца такое бывало),
    падаем на обычное открытие: файл уже существует, создавать нечего.
    Образец взят у core/state_version.
    """
    from core import store
    path = str(store.db_path())
    have = getattr(_readers, "conn", None)
    if have is not None and getattr(_readers, "path", None) == path:
        return have
    _close_reader()
    target = Path(path)
    if not target.exists():
        # Базы ещё нет: пусть её создаст и мигрирует путь записи, а не чтение.
        _connection()
    conn = None
    from urllib.parse import quote
    uri = "file:" + quote(Path(path).as_posix(), safe="/:") + "?mode=ro"
    for opener in (lambda: sqlite3.connect(uri, uri=True, check_same_thread=False),
                   lambda: sqlite3.connect(path, check_same_thread=False)):
        try:
            conn = opener()
            break
        except sqlite3.Error:
            continue
    if conn is None:
        raise WriteBusy("база не открывается даже на чтение")
    conn.row_factory = sqlite3.Row
    try:
        conn.execute("PRAGMA busy_timeout=5000")
    except sqlite3.Error:
        pass
    _readers.conn = conn
    _readers.path = path
    return conn


def _close_reader() -> None:
    conn = getattr(_readers, "conn", None)
    if conn is not None:
        try:
            conn.close()
        except Exception:
            pass
    _readers.conn = None
    _readers.path = None
